// Get 3-5 random templates for "Ideas of the day"
export const getRandomIdeas = (count: number = 4): LifeStreamTemplate[] => {
  const allTemplates = LIFE_STREAMS.flatMap(stream => 
    stream.templates.map(t => ({ ...t, streamIcon: stream.icon, streamColor: stream.color }))
  );
  const shuffled = [...allTemplates].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
};

